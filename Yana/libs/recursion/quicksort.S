	크하하하 야 이번엔 lldb가 아예 정답을 친절하게 다 불러줬네. 답은 저 목록 안에 있음:

```
(lldb) register read -f uint32_t[] v0
```
→ `[10, 20, 30, 40]`

```
(lldb) register read -f float32[] v0
```
→ 그 비트패턴을 float 4개로 해석한 값 (subnormal 근처의 이상한 수)

	포맷 이름이 `vector-uint32` 같은 게 아니라 그냥 **C 타입 이름 + `[]`** 였던 거야. `int32_t[]`, `uint8_t[]`, `float64[]` 이런 식으로 "이 128비트를 이 타입 배열로 쪼개서 보여줘" 라고 알려주는 문법.

	그리고 방금 `register read -f decimal v0` 한 건 포맷 이름은 맞게 썼는데 배열 표시(`[]`)를 안 붙여서, lldb가 128비트 전체를 그냥 하나의 거대한 정수로 읽어서 `3169126501123975826038943907850` 이런 괴물 숫자가 나온 거야. 이것도 정상 동작이고, 우리가 "쪼개서 보여줘"라고 말을 안 해준 것뿐임.

정리하면:
- `-f <type>[]` 형태로 써야 128비트를 요소별로 쪼개서 보여줌
- 요소별로 안 쪼개면 lldb는 전체 16바이트를 한 덩어리(정수/부동소수)로 취급함
